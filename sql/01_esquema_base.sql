-- 1. COMERCIOS
CREATE TABLE IF NOT EXISTS public.comercios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    nombre_negocio TEXT DEFAULT 'Comercio 001',
    titular_cuenta TEXT,
    banco TEXT,
    alias TEXT,
    cbu TEXT,
    qr_imagen_url TEXT,
    logo_url TEXT,
    admin_password TEXT
);

INSERT INTO public.comercios (id, nombre_negocio)
VALUES (1, 'Comercio 001')
ON CONFLICT (id) DO NOTHING;


-- 2. CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    nombre TEXT NOT NULL
);

INSERT INTO public.categorias (nombre, comercio_id)
SELECT 'General', 1
WHERE NOT EXISTS (SELECT 1 FROM public.categorias);


-- 3. PRODUCTOS (Todos los decimales en NUMERIC para compatibilidad con round)
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
    codigo TEXT,
    nombre TEXT NOT NULL,
    precio_costo NUMERIC(12,2) DEFAULT 0.00,
    margen_ganancia NUMERIC(12,2) DEFAULT 0.00,
    precio_venta NUMERIC(12,2) DEFAULT 0.00,
    usa_precio_manual BOOLEAN DEFAULT FALSE,
    stock_actual NUMERIC(12,3) DEFAULT 0.000,
    stock_minimo NUMERIC(12,3) DEFAULT 0.000,
    puntos_canje NUMERIC(12,2) NOT NULL DEFAULT 0,
    imagen_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 4. CLIENTES
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    nombre TEXT NOT NULL,
    telefono TEXT,
    email TEXT,
    saldo_deudor NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (saldo_deudor >= 0),
    limite_credito NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (limite_credito >= 0),
    puntos NUMERIC(12,2) DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW()
);


-- 5. VENTAS
CREATE TABLE IF NOT EXISTS public.ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    total_venta NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    puntos_ganados NUMERIC(12,2) DEFAULT 0,
    forma_pago TEXT DEFAULT 'Efectivo'
);


-- 6. DETALLE_VENTAS
CREATE TABLE IF NOT EXISTS public.detalle_ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT REFERENCES public.ventas(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE SET NULL,
    cantidad NUMERIC(12,3) NOT NULL DEFAULT 1.000,
    precio_unitario NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    costo_unitario NUMERIC(12,2) NOT NULL DEFAULT 0.00
);


-- 7. MOVIMIENTOS_CUENTA (Libreta / Cuenta Corriente)
CREATE TABLE IF NOT EXISTS public.movimientos_cuenta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
    ticket_id BIGINT REFERENCES public.ventas(id) ON DELETE SET NULL,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    descripcion TEXT,
    tipo TEXT
);


-- 8. MOVIMIENTOS_CAJA (Caja Chica / Control Diario)
CREATE TABLE IF NOT EXISTS public.movimientos_caja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comercio_id BIGINT DEFAULT 1,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto NUMERIC(12,2) NOT NULL DEFAULT 0.00,
    tipo TEXT NOT NULL,
    usuario_nombre TEXT,
    concepto TEXT
);


-- 9. FUNCIÓN ATÓMICA DE REGISTRO DE VENTAS
CREATE OR REPLACE FUNCTION public.registrar_venta_atomica(
    p_comercio_id bigint,
    p_cliente_id bigint,
    p_metodo_pago text,
    p_total numeric,
    p_items jsonb,
    p_puntos_ganados numeric DEFAULT 0
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY INVOKER
AS $$
declare
    v_venta_id   bigint;
    v_es_fiado   boolean;
    v_total_calc numeric;
    v_item       record;
    v_prod       record;
    v_cli        record;
begin
    if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
        raise exception 'El carrito está vacío.' using errcode = 'SV002';
    end if;

    if exists (
        select 1
        from jsonb_to_recordset(p_items)
             as x(producto_id bigint, cantidad numeric, precio_unitario numeric, costo_unitario numeric)
        where x.producto_id is null
           or x.cantidad is null or x.cantidad <= 0
           or x.precio_unitario is null or x.precio_unitario < 0
           or x.costo_unitario is null or x.costo_unitario < 0
    ) then
        raise exception 'Hay un ítem inválido en el carrito (producto, cantidad o precio incorrectos).'
            using errcode = 'SV002';
    end if;

    select coalesce(sum(round(x.cantidad * x.precio_unitario, 2)), 0)
      into v_total_calc
      from jsonb_to_recordset(p_items)
           as x(producto_id bigint, cantidad numeric, precio_unitario numeric, costo_unitario numeric);

    if p_total is null or abs(p_total - v_total_calc) > 0.01 then
        raise exception 'El total informado (%) no coincide con la suma de los renglones (%).',
            p_total, v_total_calc using errcode = 'SV002';
    end if;

    v_es_fiado := coalesce(p_metodo_pago, '') like 'Cuenta Corriente%';
    if v_es_fiado and p_cliente_id is null then
        raise exception 'Para vender a Cuenta Corriente tenés que elegir un cliente.' using errcode = 'SV002';
    end if;

    for v_item in
        select x.producto_id, sum(x.cantidad) as cantidad
          from jsonb_to_recordset(p_items)
               as x(producto_id bigint, cantidad numeric, precio_unitario numeric, costo_unitario numeric)
         group by x.producto_id
         order by x.producto_id
    loop
        select id, nombre, stock_actual
          into v_prod
          from productos
         where id = v_item.producto_id
           and comercio_id = p_comercio_id
           for update;

        if not found then
            raise exception 'El producto #% ya no existe en el catálogo.', v_item.producto_id
                using errcode = 'SV002';
        end if;

        if coalesce(v_prod.stock_actual, 0) < v_item.cantidad then
            raise exception '''%'': pediste % y hay % en stock.',
                v_prod.nombre, v_item.cantidad::float8, coalesce(v_prod.stock_actual, 0)::float8
                using errcode = 'SV001';
        end if;

        update productos
           set stock_actual = stock_actual - v_item.cantidad
         where id = v_item.producto_id;
    end loop;

    if p_cliente_id is not null then
        select id, nombre, saldo_deudor, limite_credito
          into v_cli
          from clientes
         where id = p_cliente_id
           and comercio_id = p_comercio_id
           for update;

        if not found then
            raise exception 'El cliente seleccionado no existe.' using errcode = 'SV002';
        end if;

        if v_es_fiado and coalesce(v_cli.limite_credito, 0) > 0
           and coalesce(v_cli.saldo_deudor, 0) + p_total > v_cli.limite_credito then
            raise exception '% superaria su limite de credito de $%.',
                v_cli.nombre, to_char(v_cli.limite_credito, 'FM999G999G990D00')
                using errcode = 'SV002';
        end if;
    end if;

    insert into ventas (comercio_id, total_venta, forma_pago, cliente_id, puntos_ganados)
    values (p_comercio_id, p_total, p_metodo_pago,
            p_cliente_id, coalesce(p_puntos_ganados, 0))
    returning id into v_venta_id;

    insert into detalle_ventas (venta_id, producto_id, cantidad, precio_unitario, costo_unitario)
    select v_venta_id, x.producto_id, x.cantidad, x.precio_unitario, x.costo_unitario
      from jsonb_to_recordset(p_items)
           as x(producto_id bigint, cantidad numeric, precio_unitario numeric, costo_unitario numeric);

    if p_cliente_id is not null then
        update clientes
           set saldo_deudor = case when v_es_fiado then round(coalesce(saldo_deudor, 0)::numeric + p_total, 2) else saldo_deudor end,
               puntos = round(coalesce(puntos, 0)::numeric + coalesce(p_puntos_ganados, 0), 2)
         where id = p_cliente_id;

        if v_es_fiado then
            insert into movimientos_cuenta (comercio_id, cliente_id, tipo, monto, descripcion, ticket_id)
            values (p_comercio_id, p_cliente_id, 'CARGO', p_total,
                    'Compra segun Ticket #' || v_venta_id, v_venta_id);
        end if;
    end if;

    return v_venta_id;
end;
$$;

REVOKE ALL ON FUNCTION public.registrar_venta_atomica(bigint, bigint, text, numeric, jsonb, numeric) FROM public;
GRANT EXECUTE ON FUNCTION public.registrar_venta_atomica(bigint, bigint, text, numeric, jsonb, numeric)
    TO anon, authenticated, service_role;


-- 10. STORAGE BUCKET PARA IMÁGENES Y LOGO
INSERT INTO storage.buckets (id, name, public)
VALUES ('productos', 'productos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Acceso publico lectura productos" ON storage.objects;
CREATE POLICY "Acceso publico lectura productos" ON storage.objects FOR SELECT TO public USING (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico subida productos" ON storage.objects;
CREATE POLICY "Acceso publico subida productos" ON storage.objects FOR INSERT TO public WITH CHECK (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico actualizacion productos" ON storage.objects;
CREATE POLICY "Acceso publico actualizacion productos" ON storage.objects FOR UPDATE TO public USING (bucket_id = 'productos') WITH CHECK (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico borrado productos" ON storage.objects;
CREATE POLICY "Acceso publico borrado productos" ON storage.objects FOR DELETE TO public USING (bucket_id = 'productos');

