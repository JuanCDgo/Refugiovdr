-- 1. COMERCIOS (Tabla principal para sistema multitenant)
CREATE TABLE IF NOT EXISTS public.comercios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL DEFAULT 'Comercio Base',
    creado_en TIMESTAMPTZ DEFAULT NOW()
);

INSERT INTO public.comercios (id, nombre) 
VALUES (1, 'Comercio Base') 
ON CONFLICT (id) DO NOTHING;


-- 2. CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);

INSERT INTO public.categorias (nombre, comercio_id)
SELECT 'General', 1 
WHERE NOT EXISTS (SELECT 1 FROM public.categorias);


-- 3. PRODUCTOS
CREATE TABLE IF NOT EXISTS public.productos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT,
    nombre TEXT NOT NULL,
    descripcion TEXT,
    precio REAL NOT NULL DEFAULT 0.0,
    costo REAL NOT NULL DEFAULT 0.0,
    stock REAL NOT NULL DEFAULT 0.0,
    stock_minimo REAL DEFAULT 0.0,
    categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 4. CLIENTES
CREATE TABLE IF NOT EXISTS public.clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL,
    telefono TEXT,
    direccion TEXT,
    email TEXT,
    saldo_deudor REAL NOT NULL DEFAULT 0.0 CHECK (saldo_deudor >= 0),
    limite_credito REAL NOT NULL DEFAULT 0.0 CHECK (limite_credito >= 0),
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 5. VENTAS
CREATE TABLE IF NOT EXISTS public.ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE SET NULL,
    total REAL NOT NULL DEFAULT 0.0,
    metodo_pago TEXT NOT NULL DEFAULT 'Efectivo',
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 6. DETALLE_VENTAS (Lo que va adentro del carrito)
CREATE TABLE IF NOT EXISTS public.detalle_ventas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id BIGINT REFERENCES public.ventas(id) ON DELETE CASCADE,
    producto_id BIGINT REFERENCES public.productos(id) ON DELETE SET NULL,
    cantidad REAL NOT NULL DEFAULT 1.0,
    precio_unitario REAL NOT NULL DEFAULT 0.0,
    subtotal REAL NOT NULL DEFAULT 0.0,
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 7. MOVIMIENTOS_CUENTA (Para la libreta y los fiados)
CREATE TABLE IF NOT EXISTS public.movimientos_cuenta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES public.clientes(id) ON DELETE CASCADE,
    ticket_id BIGINT REFERENCES public.ventas(id) ON DELETE SET NULL,
    venta_id BIGINT REFERENCES public.ventas(id) ON DELETE SET NULL,
    monto REAL NOT NULL DEFAULT 0.0,
    tipo TEXT, -- Ej: 'cargo', 'abono'
    tipo_movimiento TEXT,
    metodo_pago TEXT DEFAULT 'Efectivo',
    descripcion TEXT,
    concepto TEXT,
    usuario_id BIGINT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 8. CIERRES_CAJA
CREATE TABLE IF NOT EXISTS public.cierres_caja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_cierre TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    monto_esperado REAL NOT NULL DEFAULT 0.0,
    monto_real REAL NOT NULL DEFAULT 0.0,
    diferencia REAL NOT NULL DEFAULT 0.0,
    usuario_id BIGINT,
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 9. MOVIMIENTOS_CAJA (Caja chica, ingresos/egresos manuales a la caja)
CREATE TABLE IF NOT EXISTS public.movimientos_caja (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descripcion TEXT,
    concepto TEXT,
    categoria TEXT,
    metodo_pago TEXT DEFAULT 'Efectivo',
    monto REAL NOT NULL DEFAULT 0.0,
    tipo TEXT NOT NULL, -- 'ingreso' o 'egreso'
    usuario_id BIGINT,
    fecha TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    comercio_id BIGINT DEFAULT 1 REFERENCES public.comercios(id) ON DELETE CASCADE
);


-- 10. STORAGE BUCKET PARA IMÁGENES Y LOGO
INSERT INTO storage.buckets (id, name, public)
VALUES ('productos', 'productos', true)
ON CONFLICT (id) DO UPDATE SET public = true;

DROP POLICY IF EXISTS "Acceso publico lectura productos" ON storage.objects;
CREATE POLICY "Acceso publico lectura productos" ON storage.objects FOR SELECT TO public USING (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico subida productos" ON storage.objects;
CREATE POLICY "Acceso publico subida productos" ON storage.objects FOR INSERT TO public WITH CHECK (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico actualizacion productos" ON storage.objects;
CREATE POLICY "Acceso publico actualizacion productos" ON storage.objects FOR UPDATE TO public USING (bucket_id = 'productos') WITH CHECK (bucket_id = 'productos');

DROP POLICY IF EXISTS "Acceso publico borrado productos" ON storage.objects;
CREATE POLICY "Acceso publico borrado productos" ON storage.objects FOR DELETE TO public USING (bucket_id = 'productos');

